# Interfaces (ABCs)
class LockInterface(abc.ABC):
    """Abstract interface for locking mechanisms to ensure atomic operations."""

    @abc.abstractmethod
    async def lock(self, resource: str) -> bool:
        """Acquire a lock on the resource. Returns True if successful."""
        pass

    @abc.abstractmethod
    async def unlock(self, resource: str) -> None:
        """Release the lock on the resource."""
        pass


class VCInterface(abc.ABC):
    """Abstract interface for version control operations."""

    @abc.abstractmethod
    async def create_branch(self, name: str) -> bool:
        """Create a new branch. Returns True if successful."""
        pass

    @abc.abstractmethod
    async def switch_branch(self, name: str) -> None:
        """Switch to the specified branch."""
        pass

    @abc.abstractmethod
    async def merge_branch(self, source: str, target: str) -> bool:
        """Merge source branch into target. Returns True if successful."""
        pass


class ExecutorInterface(abc.ABC):
    """Abstract interface for executing tasks or workflows."""

    @abc.abstractmethod
    async def execute_task(self, task: Task) -> Any:
        """Execute the given task. Returns the result."""
        pass


