class ClaimTaskUseCase:
    """Use case for atomically claiming a task via adapters. Depends on LockInterface."""

    def __init__(self, lock_interface: LockInterface):
        self.lock_interface = lock_interface

    async def execute(self, task: Task) -> bool:
        """Claim the task atomically. Returns True if claimed successfully."""
        try:
            locked = await self.lock_interface.lock(f"task_{task.id}")
            if locked:
                # Note: In real implementation, would update task via repository
                logger.info("Task %s claimed successfully.", task.id)
                return True
            else:
                logger.warning("Failed to lock task %s.", task.id)
                return False
        except Exception as e:
            logger.error("Error claiming task %s: %s", task.id, e)
            raise
        finally:
            await self.lock_interface.unlock(f"task_{task.id}")


