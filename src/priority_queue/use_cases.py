class ManageBranchesUseCase:
    """Use case for Git branch creation and management. Depends on VCInterface."""

    def __init__(self, vc_interface: VCInterface):
        self.vc_interface = vc_interface

    async def execute(self, action: str, branch_name: str, target_branch: Optional[str] = None) -> bool:
        """Perform branch management action (create, switch, merge). Returns True if successful."""
        try:
            if action == "create":
                success = await self.vc_interface.create_branch(branch_name)
            elif action == "switch":
                await self.vc_interface.switch_branch(branch_name)
                success = True
            elif action == "merge" and target_branch:
                success = await self.vc_interface.merge_branch(branch_name, target_branch)
            else:
                raise ValueError("Invalid action or missing parameters.")
            logger.info("Branch action '%s' completed for %s.", action, branch_name)
            return success
        except Exception as e:
            logger.error("Error in branch management for %s: %s", branch_name, e)
            raise


class HandleErrorsUseCase:
    """Use case for handling errors with retry and exponential backoff."""

    def __init__(self, max_retries: int = 3, base_delay: float = 1.0):
        self.max_retries = max_retries
        self.base_delay = base_delay

    async def execute(self, func: Callable[[], Awaitable[Any]]) -> Any:
        """Execute the function with retry on failure. Returns the result."""
        for attempt in range(self.max_retries + 1):
            try:
                return await func()
            except Exception as e:
                if attempt < self.max_retries:
                    delay = self.base_delay * (2 ** attempt)
                    logger.warning("Attempt %d failed: %s. Retrying in %.2f seconds.", attempt + 1, e, delay)
                    await asyncio.sleep(delay)
                else:
                    logger.error("All retries exhausted: %s", e)
                    raise


